export const BRAIN_REGIONS = RAW_REGIONS.map((r) => bilingual(r));

export const REGION_MAP = Object.fromEntries(BRAIN_REGIONS.map((r) => [r.id, r]));

/** Map electrode region key ('frontal', 'motor', 'visual', ...) to region id */
export function resolveRegionId(idOrKey) {
  if (!idOrKey) return 'brain';
  const low = String(idOrKey).toLowerCase();
  if (REGION_MAP[low]) return low;
  const byEn = BRAIN_REGIONS.find(
    (r) => r.meshName.toLowerCase() === low || r.nameEn.toLowerCase().includes(low)
  );
  return byEn ? byEn.id : 'brain';
}
