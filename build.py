#!/usr/bin/env python3
"""
Bundles all ES modules under `js/` into `dist/app.bundle.js` so that NeuroLAB works:
1. Even when double-clicked directly from disk (`file:///.../index.html`) without a local server!
2. On GitHub Pages (root or `/repo-name/` subfolder)
3. On Firebase Hosting (`firebase deploy`)
4. On any local static server (`python -m http.server 5173`)
"""
import glob
import os
import posixpath
import re

ROOT = os.path.dirname(os.path.abspath(__file__))


def norm_mod_id(rel_path: str) -> str:
    p = rel_path.replace("\\", "/")
    if p.startswith("./"):
        p = p[2:]
    return p


def resolve_spec(from_mod: str, spec: str) -> str:
    if not spec.startswith("."):
        return spec
    base_dir = posixpath.dirname(from_mod)
    return posixpath.normpath(posixpath.join(base_dir, spec))


def transform_module(mod_id: str, src: str) -> str:
    out_lines = []
    export_names = []

    for line in src.splitlines():
        # 1. import * as ns from 'spec';
        m_ns = re.match(r"^\s*import\s+\*\s+as\s+([A-Za-z0-9_$]+)\s+from\s+['\"]([^'\"]+)['\"];?\s*$", line)
        if m_ns:
            ns, spec = m_ns.group(1), resolve_spec(mod_id, m_ns.group(2))
            out_lines.append(f"const {ns} = __require('{spec}');")
            continue

        # 2. import { a, b as c } from 'spec';
        m_named = re.match(r"^\s*import\s+\{([^}]+)\}\s+from\s+['\"]([^'\"]+)['\"];?\s*$", line)
        if m_named:
            items_raw, spec = m_named.group(1), resolve_spec(mod_id, m_named.group(2))
            mapped = []
            for part in items_raw.split(","):
                part = part.strip()
                if not part:
                    continue
                if " as " in part:
                    orig, alias = [x.strip() for x in part.split(" as ", 1)]
                    mapped.append(f"{orig}: {alias}")
                else:
                    mapped.append(part)
            out_lines.append(f"const {{ {', '.join(mapped)} }} = __require('{spec}');")
            continue

        # 3. export default function name(...)
        m_def_fn = re.match(r"^(\s*)export\s+default\s+function\s+([A-Za-z0-9_$]+)\s*\((.*)$", line)
        if m_def_fn:
            indent, fn_name, rest = m_def_fn.groups()
            export_names.append(("default", fn_name))
            out_lines.append(f"{indent}function {fn_name}({rest}")
            continue

        # 3b. export default ident;
        m_def_id = re.match(r"^\s*export\s+default\s+([A-Za-z0-9_$]+);?\s*$", line)
        if m_def_id:
            export_names.append(("default", m_def_id.group(1)))
            continue

        # 4. export async function / export function / export class / export const / export let
        m_exp_decl = re.match(
            r"^(\s*)export\s+(async\s+function|function|class|const|let)\s+([A-Za-z0-9_$]+)(?=\s|=|\()(.*)$",
            line,
        )
        if m_exp_decl:
            indent, kw, name, rest = m_exp_decl.groups()
            export_names.append((name, name))
            out_lines.append(f"{indent}{kw} {name}{rest}")
            continue

        # 5. Dynamic import(`../widgets/${lesson.widget}.js`) or import('./pages/playground.js')
        if "import(" in line:
            line = re.sub(
                r"import\(\s*`\.\./widgets/\$\{([^}]+)\}\.js`\s*\)",
                r"Promise.resolve(__require('js/widgets/' + (\1) + '.js'))",
                line,
            )
            line = re.sub(
                r"import\(\s*['\"]\./pages/playground\.js['\"]\s*\)",
                r"Promise.resolve(__require('js/pages/playground.js'))",
                line,
            )

        out_lines.append(line)

    for exp_key, local_name in export_names:
        out_lines.append(f"__exports.{exp_key} = {local_name};")

    return "\n".join(out_lines)


def build():
    js_files = sorted(glob.glob(os.path.join(ROOT, "js", "**", "*.js"), recursive=True))
    chunks = []
    chunks.append(
        """// Auto-generated by build.py — NeuroLAB universal bundle (supports file://, GitHub Pages, Firebase Hosting)
(async function () {
  const __registry = Object.create(null);
  const __cache = Object.create(null);

  function __define(id, factory) {
    __registry[id] = factory;
  }

  function __require(id) {
    if (__cache[id]) return __cache[id];
    const factory = __registry[id];
    if (!factory) throw new Error('Module not found: ' + id);
    const exports = {};
    __cache[id] = exports;
    factory(exports, __require);
    return exports;
  }

  // Preload Three.js & addons from CDN (works on both file:// and https:// because jsDelivr sets CORS *)
  try {
    const [THREE, OrbitMod, GLTFMod, DracoMod] = await Promise.all([
      import('https://cdn.jsdelivr.net/npm/three@0.169.0/build/three.module.js'),
      import('https://cdn.jsdelivr.net/npm/three@0.169.0/examples/jsm/controls/OrbitControls.js'),
      import('https://cdn.jsdelivr.net/npm/three@0.169.0/examples/jsm/loaders/GLTFLoader.js'),
      import('https://cdn.jsdelivr.net/npm/three@0.169.0/examples/jsm/loaders/DRACOLoader.js'),
    ]);
    __cache['three'] = THREE;
    __cache['three/addons/controls/OrbitControls.js'] = OrbitMod;
    __cache['three/addons/loaders/GLTFLoader.js'] = GLTFMod;
    __cache['three/addons/loaders/DRACOLoader.js'] = DracoMod;
  } catch (err) {
    console.warn('3D library CDN load warning:', err);
  }
"""
    )

    for fpath in js_files:
        rel = os.path.relpath(fpath, ROOT)
        mod_id = norm_mod_id(rel)
        with open(fpath, encoding="utf-8") as f:
            src = f.read()
        body = transform_module(mod_id, src)
        chunks.append(f"\n  // === {mod_id} ===\n  __define('{mod_id}', function (__exports, __require) {{\n{body}\n  }});\n")

    chunks.append("\n  // Boot application\n  __require('js/app.js');\n})();\n")

    dist_dir = os.path.join(ROOT, "dist")
    os.makedirs(dist_dir, exist_ok=True)
    out_path = os.path.join(dist_dir, "app.bundle.js")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(chunks))
    print(f"Built {out_path} ({os.path.getsize(out_path)} bytes) from {len(js_files)} modules.")


if __name__ == "__main__":
    build()
